// Type for the translation keys
export type TranslationKey = keyof typeof HINDI_TRANSLATIONS;

// Simple translation function
export function t(key: string, lang: "hi" | "en" = "hi"): string {
    if (lang === "en") return key;

    const keys = key.split(".");
    let value: any = HINDI_TRANSLATIONS;

    for (const k of keys) {
        if (value && typeof value === "object" && k in value) {
            value = value[k];
        } else {
            return key; // Return original key if translation not found
        }
    }

    return typeof value === "string" ? value : key;
}

